# Release step: fails when
#   - VERSION or debian/changelog differ from the tag,
#   - a document does not carry the version of the tag in its first lines,
#   - the brochure's footer does not carry the version,
#   - an image a document references is missing.
# The documentation is released with every version of the projects, so every release
# bumps the version lines (replaces the old "unchanged since the previous tag" check).
#
#   scripts/check-manual.sh v0.9.10

set -eu
cd "$(dirname "$0")/.."

TAG=$1
VERSION=${TAG#v}
fail=0

if [ "$(cat VERSION)" != "$VERSION" ]; then
	echo "::error file=VERSION::VERSION is $(cat VERSION), the tag is $TAG"
	fail=1
fi
DV=$(echo "$VERSION" | sed 's/-/~/')
PV=$(sed -n '1s/^[^(]*(\(.*\)).*/\1/p' debian/changelog)
if [ "${PV%-*}" != "$DV" ]; then
	echo "::error file=debian/changelog::the changelog is at $PV, the tag needs $DV-<revision>"
	fail=1
fi

for f in manual/app/*/manual.md manual/app/*/quickstart.md manual/app/*/connectors/*.md \
	manual/server/*/admin.md manual/desktop/*/desktop.md; do
	[ -f "$f" ] || continue
	if ! head -n 12 "$f" | grep -q "\b$VERSION\b"; then
		echo "::error file=$f::the document does not mention version $VERSION in its first lines"
		fail=1
	fi
	dir=$(dirname "$f")
	for img in $(grep -o '!\[[^]]*\]([^)]*)' "$f" | sed 's/.*(\([^)]*\))/\1/'); do
		case "$img" in diagrams/*) continue ;; esac	# generated by the build
		if [ ! -f "$dir/$img" ]; then
			echo "::error file=$f::missing image $img"
			fail=1
		fi
	done
done

# the brochure's footer carries the version too
if ! grep -q "Versione $VERSION " brochure/brochure.html; then
	echo "::error file=brochure/brochure.html::the brochure's footer does not say version $VERSION"
	fail=1
fi

[ $fail -eq 0 ] && echo "documentation ok for $VERSION"
exit $fail
